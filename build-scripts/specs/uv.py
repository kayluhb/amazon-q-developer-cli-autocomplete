"""Builds specs/uv.ts from uv's help output. To regenerate after a uv release:

    git -C build/autocomplete-specs show HEAD:src/uv.ts > /tmp/uv.upstream.ts
    python3 build-scripts/specs/uv.py /tmp/uv.upstream.ts uvx --from uv@latest uv > specs/uv.ts
    npx prettier --write specs/uv.ts

Everything after the upstream file is the command that runs uv (default: `uv`). The script only
runs `uv [<command>...] --help` and `uv --version`. Pass `--json` first to print the crawled tree
instead of the spec.

uv's help is generated by clap, so every command prints the same sections ("Commands:",
"Arguments:", "Options:", "Index options:", ...). A root option that every command's help lists
(except `uv help`, which lists none) is persistent and left out of the subcommands. Other root
options stay on the root only (`-V/--version`) or on the commands whose help lists them
(`--offline` is hidden on `uv audit`, for example). Options shared by several commands are emitted
once as named constants.

clap's help shows no `...` for options that take a value more than once, so REPEATABLE lists them.

Dynamic suggestions reuse upstream's hand-written generators, which are copied over verbatim."""

import json
import os
import re
import subprocess
import sys

args = sys.argv[1:]
DUMP_JSON = args[:1] == ["--json"]
if DUMP_JSON:
    args = args[1:]
upstream = open(args[0]).read()
UV = args[1:] or ["uv"]
ENV = {**os.environ, "NO_COLOR": "1", "UV_NO_CONFIG": "1"}

# Upstream's hand-written generators, everything before its option definitions
PRELUDE = upstream[
    upstream.index("const dependenciesGenerator") : upstream.index(
        "// ////////////////////////////////////////////////////////////////// Options"
    )
]


class Raw(str):
    """Emitted as-is instead of as a string literal."""


def run(argv: list[str]) -> str:
    result = subprocess.run([*UV, *argv], capture_output=True, text=True, env=ENV, stdin=subprocess.DEVNULL, timeout=30)
    if result.returncode != 0:
        sys.exit(f"`uv {' '.join(argv)}` failed: {result.stderr}")
    return result.stdout


def sections(text: str) -> dict[str, list[str]]:
    """Split help output into {"Index options": [entry, ...]}, joining wrapped lines of an entry."""
    out: dict[str, list[str]] = {}
    current = None
    for line in text.splitlines():
        if re.fullmatch(r"[A-Z][A-Za-z ]*:", line):
            current = out.setdefault(line[:-1], [])
        elif not line.strip():
            continue
        elif not line.startswith(" "):
            current = None
        elif current is not None:
            indent = len(line) - len(line.lstrip())
            if indent <= 6:
                current.append(line.strip())
            else:
                current[-1] += " " + line.strip()
    return out


OPTION_RE = re.compile(r"(?:(-\w)(?:, )?)?(--[\w-]+)?(\.\.\.)?(?: <([^>]+)>)?(\.\.\.)?(?:\s+(.*))?")
ARG_RE = re.compile(r"([<\[])([^>\]]+)[>\]](\.\.\.)?(?:\s+(.*))?")
USAGE_ARG_RE = re.compile(r"([<\[])([A-Z_]+)[>\]](\.\.\.)?")
COMMAND_RE = re.compile(r"(\S+)(?:\s+(.*))?")


def bracket(desc: str, key: str) -> tuple[str, str | None]:
    """Remove `[key: value]` from desc and return (desc, value)."""
    m = re.search(rf"\s*\[{key}: ([^\]]*)\]", desc)
    if not m:
        return desc, None
    return desc[: m.start()] + desc[m.end() :], m.group(1)


def parse_option(entry: str) -> dict:
    m = OPTION_RE.fullmatch(entry)
    if not m or not (m.group(1) or m.group(2)):
        sys.exit(f"can't parse option: {entry!r}")
    short, long, rep1, arg, rep2, desc = m.groups()
    desc = re.sub(r"\s*\[env: [^\]]*\]", "", desc or "")
    desc, values = bracket(desc, "possible values")
    desc, default = bracket(desc, "default")
    return {
        "names": [n for n in (short, long) if n],
        "arg": arg,
        "repeatable": bool(rep1 or rep2),
        "values": values.split(", ") if values else None,
        "default": default,
        "description": desc.strip(),
    }


def parse_argument(entry: str) -> dict:
    m = ARG_RE.fullmatch(entry)
    if not m:
        sys.exit(f"can't parse argument: {entry!r}")
    bracket_open, name, variadic, desc = m.groups()
    desc = re.sub(r"\s*\[env: [^\]]*\]", "", desc or "")
    desc, values = bracket(desc, "possible values")
    desc, default = bracket(desc, "default")
    return {
        "name": name,
        "optional": bracket_open == "[",
        "variadic": bool(variadic),
        "values": values.split(", ") if values else None,
        "default": default,
        "description": desc.strip(),
    }


def crawl(path: list[str], description: str) -> dict:
    text = run([*path, "--help"])
    secs = sections(text)
    node = {
        "name": path[-1] if path else "uv",
        "aliases": [],
        "description": description,
        "args": [parse_argument(e) for e in secs.pop("Arguments", [])],
        "subcommands": [],
    }
    for entry in secs.pop("Commands", []):
        name, desc = COMMAND_RE.fullmatch(entry).groups()
        desc, aliases = bracket(desc or "", "aliases?")
        child = crawl([*path, name], desc.strip())
        child["aliases"] = aliases.split(", ") if aliases else []
        node["subcommands"].append(child)
    if not node["args"]:
        # Some commands (`run`, `help`) only name their arguments in the usage line
        usage = next(line for line in text.splitlines() if line.startswith("Usage: "))
        for m in USAGE_ARG_RE.finditer(usage.partition("[OPTIONS]")[2]):
            if m.group(2) != "COMMAND" or not node["subcommands"]:
                node["args"].append(parse_argument(m.group(0)))
    secs.pop("Usage", None)
    node["options"] = [parse_option(e) for entries in secs.values() for e in entries]
    return node


version = run(["--version"]).strip()
tree = crawl([], "An extremely fast Python package manager")
if DUMP_JSON:
    print(json.dumps(tree, indent=1))
    sys.exit()

TOP_COMMANDS = [c["name"] for c in tree["subcommands"]]

# Completions the help text can't tell us about, keyed by "<command path> <--flag or ARG>"
OVERRIDES: dict[str, dict] = {
    "run COMMAND": {"generators": Raw("commandGenerator"), "template": "filepaths"},
    "remove PACKAGES": {"generators": Raw("dependenciesGenerator")},
    "help COMMAND": {"suggestions": TOP_COMMANDS},
}
# Commands whose trailing arguments belong to the command they run
PASSTHROUGH = {"run", "tool run"}
# Options that can be given more than once, on every command that has them...
REPEATABLE = set(
    """
    --with --with-editable --with-requirements --index --extra-index-url --find-links --extra
    --no-extra --group --no-group --only-group --upgrade-package --upgrade-group
    --reinstall-package --refresh-package --no-build-package --no-binary-package
    --no-build-isolation-package --no-sources-package --config-setting --config-settings-package
    --allow-insecure-host --env-file --exclude-newer-package --prerelease-package --ignore
    --ignore-until-fixed --requirements --constraints --overrides --build-constraints --excludes
    --exclude --bump
""".split()
)
# ...or only on these commands ("<command path> <flag>")
REPEATABLE |= {f"{c} --package" for c in ("sync", "export", "check", "tree", "pip tree")}
REPEATABLE |= {"pip install --editable"}
# Commands where a REPEATABLE flag takes a single value
NOT_REPEATABLE = {"add --group", "remove --group", "publish --index"}
FOLDER_ARGS = {"DIRECTORY", "PROJECT", "CACHE_DIR", "OUT_DIR", "INSTALL_DIR", "TARGET", "PREFIX"}
FILE_ARGS = re.compile(r"FILE|PATH|REQUIREMENTS|CONSTRAINT|OVERRIDE|SCRIPT|^SRC$")


def tidy(description: str) -> str:
    """Match the fig linter's description style: capitalised, no trailing dot."""
    description = description.strip().removesuffix(".")
    return description[:1].upper() + description[1:]


def completion(key: str, meta: str, values: list[str] | None) -> dict:
    if key in OVERRIDES:
        return OVERRIDES[key]
    if values:
        return {"suggestions": values}
    if meta in FOLDER_ARGS:
        return {"template": "folders"}
    if FILE_ARGS.search(meta):
        return {"template": "filepaths"}
    return {}


def option(opt: dict, path: list[str]) -> dict:
    names = opt["names"]
    out: dict = {"name": names[0] if len(names) == 1 else names, "description": tidy(opt["description"])}
    if opt["description"].startswith("(Deprecated"):
        out["deprecated"] = True
    if opt["arg"]:
        args: dict = {"name": re.sub(r"\[.*\]$", "", opt["arg"])}  # BUMP[=VALUE] -> BUMP
        args.update(completion(" ".join([*path, names[-1]]), opt["arg"], opt["values"]))
        if opt["default"]:
            args["default"] = opt["default"]
        out["args"] = args
    key = " ".join([*path, names[-1]])
    if opt["repeatable"] or (key not in NOT_REPEATABLE and (names[-1] in REPEATABLE or key in REPEATABLE)):
        out["isRepeatable"] = True
    return out


def argument(arg: dict, path: list[str]) -> dict:
    out: dict = {"name": arg["name"]}
    if arg["description"]:
        out["description"] = tidy(arg["description"])
    if arg["optional"]:
        out["isOptional"] = True
    if arg["variadic"]:
        out["isVariadic"] = True
    out.update(completion(" ".join([*path, arg["name"]]), arg["name"], arg["values"]))
    if " ".join(path) in PASSTHROUGH and arg["name"] == "COMMAND":
        out["isCommand"] = True  # `uv run pytest -<tab>` completes with pytest's spec
    if arg["default"]:
        out["default"] = arg["default"]
    return out


def names_in(node: dict):
    """Yield the set of option names that each command below node lists."""
    for c in node["subcommands"]:
        if c["name"] != "help":
            yield {tuple(o["names"]) for o in c["options"]}
            yield from names_in(c)


GLOBAL_NAMES = set.intersection(*names_in(tree)) & {tuple(o["names"]) for o in tree["options"]}


def command(node: dict, path: list[str]) -> dict:
    names = [node["name"], *node["aliases"]]
    out: dict = {"name": names[0] if len(names) == 1 else names, "description": tidy(node["description"])}
    if node["subcommands"]:
        out["subcommands"] = [command(c, [*path, c["name"]]) for c in node["subcommands"]]
    opts = [option(o, path) for o in node["options"] if tuple(o["names"]) not in GLOBAL_NAMES]
    if opts:
        out["options"] = opts
    if node["args"]:
        args = [argument(a, path) for a in node["args"]]
        out["args"] = args[0] if len(args) == 1 else args
    if " ".join(path) in PASSTHROUGH:
        out["parserDirectives"] = {"optionsMustPrecedeArguments": True}
    return out


def emit(value) -> str:
    if isinstance(value, Raw):
        return str(value)
    if isinstance(value, dict):
        return "{" + ", ".join(f"{k}: {emit(v)}" for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "[" + ", ".join(emit(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=False)


spec = command(tree, [])
spec["options"] = [
    {**option(o, []), "isPersistent": True} if tuple(o["names"]) in GLOBAL_NAMES else option(o, [])
    for o in tree["options"]
]

# Hoist options used by more than one command into named constants
counts: dict[str, int] = {}


def count(cmd: dict):
    for o in cmd.get("options", []):
        counts[emit(o)] = counts.get(emit(o), 0) + 1
    for c in cmd.get("subcommands", []):
        count(c)


for sub in spec["subcommands"]:
    count(sub)
shared: dict[str, str] = {}
for text, n in counts.items():
    if n < 2:
        continue
    names = json.loads(re.search(r'name: ("[^"]*"|\[[^\]]*\])', text).group(1))
    long = names if isinstance(names, str) else names[-1]
    var = re.sub(r"-(\w)", lambda m: m.group(1).upper(), long.lstrip("-")) + "Option"
    base, i = var, 2
    while var in shared.values():
        var, i = f"{base}{i}", i + 1
    shared[text] = var


def hoist(cmd: dict):
    if "options" in cmd:
        cmd["options"] = [Raw(shared[emit(o)]) if emit(o) in shared else o for o in cmd["options"]]
    for c in cmd.get("subcommands", []):
        hoist(c)


for sub in spec["subcommands"]:
    hoist(sub)

print(f"// Generated by build-scripts/specs/uv.py from {version}; don't edit by hand")
print(PRELUDE)
for text, var in shared.items():
    print(f"const {var}: Fig.Option = {text};\n")
print(f"const completionSpec: Fig.Spec = {emit(spec)};\n")
print("export default completionSpec;")
